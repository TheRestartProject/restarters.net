// The share images for impact ranges 1-5 have a footnote baked into the PNG in English.  We paint over it and
// write a translated version instead.  Range 6 images have no footnote.

export function hasBakedFootnote(imageName) {
  const m = /^ImpactRange(\d+)/.exec(imageName || '')
  return !!m && parseInt(m[1]) <= 5
}

export function footnoteRange(imageName) {
  const m = /^ImpactRange(\d+)/.exec(imageName || '')
  return m ? parseInt(m[1]) : null
}

// Range 5 (hectares) images carry a different footnote from ranges 1-4.
export function footnoteKey(imageName) {
  return footnoteRange(imageName) === 5 ? 'partials.share_modal_footnote_hectares' : 'partials.share_modal_footnote'
}

// Returns the rectangle to blank, and where/how to draw the replacement text, as fractions of the canvas size.
export function footnoteLayout(portrait) {
  if (portrait) {
    // Square images: footnote spans the width, with "generated by restarters.net" on a line below.
    return {x: 0, y: 0.905, w: 1, h: 0.04, textY: 0.9265, fontH: 0.024, textX: 0.04, maxW: 0.92, centre: true}
  }

  // Landscape: footnote is bottom left, "generated by restarters.net" is bottom right (from ~0.717 of width in
  // range 5, ~0.73 in ranges 1-4).  Baked footnote text starts at ~0.909 of the height in ranges 3-5.
  return {x: 0, y: 0.905, w: 0.71, h: 0.095, textY: 0.9535, fontH: 0.032, textX: 0.03, maxW: 0.67, centre: false}
}
